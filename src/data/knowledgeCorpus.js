export function getCorpusByCategory(category) {
  return knowledgeCorpus.filter((item) => item.category === category);
}

export function searchCorpus(query) {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return knowledgeCorpus;

  return knowledgeCorpus.filter((item) => {
    const searchableText = [
      item.title,
      item.category,
      item.summary,
      ...item.learningUses,
      ...item.suggestedPrompts,
      ...item.accessibilityTargets
    ]
      .join(" ")
      .toLowerCase();
    return searchableText.includes(normalized);
  });
}

export function getCorpusById(id) {
  return knowledgeCorpus.find((item) => item.id === id);
}

export function mapDokTargetsToCognitiveTargets(dokTargets = []) {
  const targetSet = new Set();
  dokTargets.forEach((dok) => {
    if (dok === 1) {
      targetSet.add("Recognition");
      targetSet.add("Comprehension");
    }
    if (dok === 2) {
      targetSet.add("Comprehension");
      targetSet.add("Application");
    }
    if (dok === 3) {
      targetSet.add("Strategic Analysis");
      targetSet.add("Integrative Transfer");
    }
    if (dok === 4) {
      targetSet.add("Integrative Transfer");
      targetSet.add("Reflective Mastery");
    }
  });
  return [...targetSet];
}

export function getRecommendedCorpusItems({ theme = "", dokLevel, accessibilityLevel } = {}) {
  const themeMatches = searchCorpus(theme);
  const pool = themeMatches.length ? themeMatches : knowledgeCorpus;

  return [...pool]
    .map((item) => {
      const cognitiveTargets = mapDokTargetsToCognitiveTargets(item.dokTargets);
      const dokScore = item.dokTargets.includes(Number(dokLevel)) || cognitiveTargets.includes(dokLevel) ? 2 : 0;
      const accessScore = item.accessibilityTargets.includes(accessibilityLevel) ? 2 : 0;
      const themeScore = themeMatches.includes(item) ? 2 : 0;
      return { item: { ...item, cognitiveTargets }, score: dokScore + accessScore + themeScore };
    })
    .sort((first, second) => second.score - first.score || first.item.title.localeCompare(second.item.title))
    .slice(0, 5)
    .map(({ item }) => item);
}
